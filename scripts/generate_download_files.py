#!/usr/bin/env python3
"""Refresh the document inventory and the downloads page's static file list."""

import hashlib
import html
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
DOCUMENT_TYPES = {".pdf", ".doc", ".docx", ".odt", ".ppt", ".pptx", ".odp", ".xls", ".xlsx", ".ods", ".epub"}
TITLES = {
    "Bachelor_Thesis.pdf": "Bachelor thesis",
    "CV_Academic.pdf": "Academic CV",
    "ebs_mnih.pdf": "Empirical Bernstein stopping rule",
    "poster.pdf": "DPG Spring Meeting poster",
    "seminar_thesis.pdf": "Bachelor thesis presentation",
}


def format_size(size):
    if size < 1_000:
        return f"{size} B"
    if size < 1_000_000:
        return f"{size / 1_000:.0f} kB"
    return f"{size / 1_000_000:.1f} MB"


def generate():
    files = []
    for path in sorted((DOCS / "files").rglob("*")):
        if not path.is_file() or path.is_symlink() or path.suffix.lower() not in DOCUMENT_TYPES:
            continue
        relative = path.relative_to(DOCS).as_posix()
        files.append({
            "path": relative,
            "title": TITLES.get(path.name, path.stem.replace("_", " ")),
            "bytes": path.stat().st_size,
            # Hash the whole case-sensitive path to keep Abacus keys stable and under 64 characters.
            "key": "download-" + hashlib.sha256(relative.encode()).hexdigest()[:40],
        })

    source = "// Generated by scripts/generate_download_files.py.\nwindow.downloadFiles = "
    source += json.dumps(files, indent=4, ensure_ascii=False) + ";\n"
    (DOCS / "js" / "download-files.js").write_text(source)

    page = DOCS / "downloads.html"
    content = page.read_text()
    start = "                <!-- document-list:start -->\n"
    end = "                <!-- document-list:end -->"
    before, remaining = content.split(start, 1)
    _, after = remaining.split(end, 1)
    rows = []
    for item in files:
        path = html.escape(item["path"], quote=True)
        title = html.escape(item["title"])
        file_type = Path(item["path"]).suffix.lstrip(".").upper()
        rows.append(f'''                <li data-file="{path}"><a class="pdf-link" href="{path}" target="_blank" rel="noopener">{title}</a> <span class="file-meta">{file_type} &middot; {format_size(item["bytes"])} &middot; <span class="visitor-number download-count" aria-label="Download count not loaded">&mdash;</span> download clicks</span></li>
''')
    page.write_text(before + start + "".join(rows) + end + after)
    print(f"Updated {len(files)} downloadable documents.")


if __name__ == "__main__":
    generate()
